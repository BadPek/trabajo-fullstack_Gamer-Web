#!/bin/bash
set -euo pipefail

: "${TEST_SCHEMA_PASSWORD:?TEST_SCHEMA_PASSWORD must be set}"

sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = XEPDB1;
CREATE USER GZ_TEST_CATALOGO IDENTIFIED BY "${TEST_SCHEMA_PASSWORD}" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA 500M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE TRIGGER TO GZ_TEST_CATALOGO;
CREATE USER GZ_TEST_AUTH IDENTIFIED BY "${TEST_SCHEMA_PASSWORD}" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA 500M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE TRIGGER TO GZ_TEST_AUTH;
CREATE USER GZ_TEST_CARRITO IDENTIFIED BY "${TEST_SCHEMA_PASSWORD}" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA 500M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE TRIGGER TO GZ_TEST_CARRITO;
CREATE USER GZ_TEST_CONTACTO IDENTIFIED BY "${TEST_SCHEMA_PASSWORD}" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA 500M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE TRIGGER TO GZ_TEST_CONTACTO;
CREATE USER GZ_TEST_PEDIDO IDENTIFIED BY "${TEST_SCHEMA_PASSWORD}" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP QUOTA 500M ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE TRIGGER TO GZ_TEST_PEDIDO;
EXIT
SQL
